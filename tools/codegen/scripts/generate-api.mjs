import { canonicalType } from './type-contracts.mjs';
import { runtimeExport } from './public-exports.mjs';
import { componentContract, renderContracts } from './react-contracts.mjs';
import { renderPackageMap } from './package-map.mjs';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ts = require('typescript');
const root = path.resolve(
	path.dirname(fileURLToPath(import.meta.url)),
	'../../..'
);
const core = path.join(root, 'packages/ui-components');
const react = path.resolve(core, '../react-ui-components');
const check = process.argv.includes('--check');
const metadata = JSON.parse(
	readFileSync(path.join(core, 'docs/docs.json'), 'utf8')
);
const packageInfo = JSON.parse(
	readFileSync(path.join(core, 'package.json'), 'utf8')
);

/** Escape generated metadata for a single Markdown table cell. */
const cell = (value) =>
	String(value ?? '')
		.replaceAll('|', '\\|')
		.replaceAll('\n', ' ')
		.replaceAll('`', '\\`');

/** Compare or replace deterministic output; never silently accept a missing build. */
const emit = (filename, content) => {
	if (check) {
		if (
			!existsSync(filename) ||
			readFileSync(filename, 'utf8') !== content
		) {
			throw new Error(`Stale catalog: ${filename}`);
		}
	} else {
		writeFileSync(filename, content);
	}
};

// Stencil reference ids include machine-specific dependency-store paths; location/path/name
// carry the semantic reference without an installation-layout identifier.
/** Normalize compiler type ordering and literal choices, retaining portable reference locations. */
const normalizeMembers = (items) =>
	JSON.parse(
		JSON.stringify(
			items.map((item) => ({
				...item,
				...(item.type ? { type: canonicalType(item.type) } : {}),
				...(item.complexType?.resolved
					? {
						complexType: {
							...item.complexType,
							resolved: canonicalType(
								item.complexType.resolved
							)
						}
					}
					: {}),
				// Stencil splits non-literal unions into incomplete type fragments; the complete type is authoritative.
				...(item.values
					? {
						values: item.values.filter((entry) =>
							Object.hasOwn(entry, 'value')
						)
					}
					: {})
			})),
			(key, value) =>
				key === 'references'
					? Object.fromEntries(
						Object.entries(value).map(([name, reference]) => {
							const { id: _id, ...portableReference } =
									reference;

							return [name, portableReference];
						})
					)
					: value
		)
	);
const components = Object.fromEntries(
	[...metadata.components]
		.sort((a, b) => (a.tag < b.tag ? -1 : a.tag > b.tag ? 1 : 0))
		.map((item) => [
			item.tag,
			{
				source: item.filePath,
				description: item.docs,
				encapsulation: item.encapsulation,
				props: normalizeMembers(item.props),
				events: normalizeMembers(item.events),
				methods: normalizeMembers(item.methods),
				slots: item.slots,
				cssProperties: item.styles,
				parts: item.parts
			}
		])
);
const manifest = {
	schemaVersion: 1,
	package: packageInfo.name,
	versionSource: 'package.json',
	compiler: metadata.compiler,
	components
};
const digest = createHash('sha256')
	.update(JSON.stringify(manifest))
	.digest('hex');

emit(
	path.join(core, 'manifest.json'),
	JSON.stringify({ ...manifest, contentHash: digest }, null, 2) + '\n'
);
emit(
	path.join(core, 'API.md'),
	`# ${packageInfo.name} component API\n\nGenerated by \`pnpm docs:generate\` after Stencil builds \`docs/docs.json\`. Do not edit.\nRead the adjacent package.json for the installed version. Source manifests can use placeholder release versions.\n\nStart with the tag below, then read \`manifest.json\` for exact props, defaults, events, methods, slots and CSS properties. An absent description is not proof that a capability is supported.\n\n| Component | Props | Events | CSS properties |\n| --- | --- | --- | --- |\n` +
		Object.entries(components)
			.map(
				([tag, item]) =>
					`| ${tag} | ${cell(
						item.props
							.map(
								(p) =>
									p.name + (p.required ? ' (required)' : '')
							)
							.join(', ')
					)} | ${cell(
						item.events.map((e) => e.event).join(', ')
					)} | ${cell(
						item.cssProperties.map((s) => s.name).join(', ')
					)} |`
			)
			.join('\n') +
		'\n'
);

const reactInfo = JSON.parse(
	readFileSync(path.join(react, 'package.json'), 'utf8')
);
const mappings = Object.entries(reactInfo.exports)
	.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
	.filter(
		([entry]) =>
			entry !== './manifest.json' && !entry.startsWith('./assets/')
	)
	.map(([entry, target]) => {
		if (
			typeof target.types !== 'string' ||
			!target.types.startsWith('./dist/types/') ||
			!target.types.endsWith('.d.ts')
		) {
			throw new Error(`Unsupported React public entry mapping: ${entry}`);
		}

		return [
			entry,
			path.join(
				react,
				target.types
					.replace('./dist/types/', 'src/')
					.replace(/\.d\.ts$/, '.ts')
			)
		];
	});
const entries = mappings.map(([entry]) => entry);
const filenames = mappings.map(([, file]) => file);

for (const file of filenames) {
	if (!existsSync(file)) {
		throw new Error(`Missing React entry ${file}`);
	}
}

if (!existsSync(path.join(react, 'src/stencil-generated/index.ts'))) {
	throw new Error('Build Stencil to generate React wrappers first.');
}
const program = ts.createProgram(filenames, {
	module: ts.ModuleKind.ESNext,
	moduleResolution: ts.ModuleResolutionKind.Bundler,
	target: ts.ScriptTarget.ES2020,
	jsx: ts.JsxEmit.ReactJSX,
	skipLibCheck: true,
	// Retain explicit null and undefined in the published public contracts.
	strictNullChecks: true,
	baseUrl: react,
	paths: {
		'@kelvininc/ui-components': ['../ui-components/src/index.ts'],
		'@kelvininc/ui-components/components': [
			'../ui-components/src/components.d.ts'
		],
		'@kelvininc/ui-components/loader': [
			'../ui-components/loader/index.d.ts'
		]
	}
});

// An unresolved export-star would otherwise silently disappear from the index.
for (const source of program.getSourceFiles()) {
	if (source.fileName.includes('/node_modules/')) {
		continue;
	}

	for (const statement of source.statements) {
		if (
			ts.isExportDeclaration(statement) &&
			statement.moduleSpecifier &&
			ts.isStringLiteral(statement.moduleSpecifier)
		) {
			const resolved = ts.resolveModuleName(
				statement.moduleSpecifier.text,
				source.fileName,
				program.getCompilerOptions(),
				ts.sys
			).resolvedModule;

			if (!resolved) {
				throw new Error(
					`Unresolved public barrel in ${source.fileName}: ${statement.moduleSpecifier.text}`
				);
			}
		}
	}
}
const checker = program.getTypeChecker();
const nativeComponents = {};
const exportsByEntry = Object.fromEntries(
	entries.map((entry, index) => {
		const source = program.getSourceFile(filenames[index]);
		const symbol = checker.getSymbolAtLocation(source);

		if (!symbol) {
			throw new Error(`No exports in ${entry}`);
		}

		return [
			entry,
			checker
				.getExportsOfModule(symbol)
				.map((item) => {
					const target =
						item.flags & ts.SymbolFlags.Alias
							? checker.getAliasedSymbol(item)
							: item;

					if (!target.declarations?.length) {
						throw new Error(
							`Unresolved public export ${entry}:${item.name}`
						);
					}

					if (
						runtimeExport(ts, program, checker, source, item.name)
					) {
						const contract = componentContract(
							ts,
							checker,
							target,
							item.name,
							react
						);

						if (contract) {
							nativeComponents[item.name] ??= {
								...contract,
								entries: []
							};
							nativeComponents[item.name].entries.push(entry);
						}
					}

					return {
						name: item.name,
						kind: runtimeExport(
							ts,
							program,
							checker,
							source,
							item.name
						)
							? 'value'
							: 'type',
						description: ts.displayPartsToString(
							target.getDocumentationComment(checker)
						)
					};
				})
				.sort((a, b) =>
					a.name < b.name ? -1 : a.name > b.name ? 1 : 0
				)
		];
	})
);

emit(
	path.join(react, 'manifest.json'),
	JSON.stringify(
		{
			schemaVersion: 1,
			package: reactInfo.name,
			versionSource: 'package.json',
			componentMetadata: '@kelvininc/ui-components/manifest.json',
			componentContentHash: digest,
			entries: exportsByEntry,
			components: nativeComponents
		},
		null,
		2
	) + '\n'
);
emit(
	path.join(react, 'API.md'),
	`# ${reactInfo.name} exports\n\nGenerated from public source entry points by the repository's \`docs:generate\`. Do not edit.\nRead the adjacent package.json for its version and installed declarations for signatures; Stencil wrapper props, events, slots and CSS properties are in the matching \`@kelvininc/ui-components/manifest.json\`. React-authored component contracts follow the export tables below.\n\n` +
		entries
			.map(
				(entry) =>
					`## ${reactInfo.name}${
						entry === '.' ? '' : entry.slice(1)
					}\n\n| Export | Kind | Description |\n| --- | --- | --- |\n` +
					exportsByEntry[entry]
						.map(
							(item) =>
								`| ${item.name} | ${item.kind} | ${cell(
									item.description
								)} |`
						)
						.join('\n')
			)
			.join('\n\n') +
		'\n' +
		renderContracts(
			reactInfo.name,
			nativeComponents,
			cell,
			`${reactInfo.repository.url.replace(
				/\/$/,
				''
			)}/blob/dev/packages/react-ui-components/`
		)
);
emit(path.join(root, 'PACKAGES.md'), renderPackageMap(root));
console.log(
	`Catalog ${check ? 'verified' : 'generated'}: ${
		Object.keys(components).length
	} components; ${entries
		.map((e) => `${e}: ${exportsByEntry[e].length}`)
		.join(', ')}.`
);
