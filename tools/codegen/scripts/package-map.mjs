import { globSync, readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';

const purposes = {
	'@kelvininc/ui-components':
		'Stencil controls, shared icons and design tokens',
	'@kelvininc/react-ui-components':
		'React bindings, native React controls and hooks',
	'@kelvininc/react-storybook':
		'Interactive component examples and documentation',
	'@kelvininc/ui-codegen':
		'Catalog generation for both UI packages and this map'
};

/** Generate workspace facts; purposes are maintained explicitly by each workspace owner. */
export const renderPackageMap = (root) => {
	const rows = globSync(
		[
			'packages/*/package.json',
			'apps/*/package.json',
			'tools/*/package.json'
		],
		{ cwd: root }
	)
		.sort()
		.map((file) => {
			const pkg = JSON.parse(readFileSync(path.join(root, file), 'utf8'));
			const dir = path.dirname(file);
			const available = new Set(readdirSync(path.join(root, dir)));
			const readme = available.has('README.md')
				? 'README.md'
				: 'readme.md';
			const links = ['API.md', 'manifest.json', readme]
				.filter((name) => available.has(name))
				.map((name) => `[${name}](${dir}/${name})`);

			return `| [${pkg.name}](${file}) | ${
				pkg.private ? 'internal' : 'published'
			} | ${
				purposes[pkg.name] ||
				pkg.description ||
				'Document workspace purpose in tools/codegen/scripts/package-map.mjs'
			} | ${
				Object.keys(pkg.exports || {}).join(', ') || 'internal commands'
			} | ${links.join(', ')} |`;
		});

	return (
		'# UI package map\n\nGenerated by `pnpm docs:generate`. Package metadata owns public entry points; purpose descriptions are maintained in tools/codegen/scripts/package-map.mjs. Each workspace owns its source and contracts. Use the installed package version when consuming a catalog.\n\n| Workspace | Distribution | Responsibility | Public entries | Discovery |\n| --- | --- | --- | --- | --- |\n' +
		rows.join('\n') +
		'\n'
	);
};
